import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const gameDataRoot =
  'https://raw.githubusercontent.com/Kengxxiao/ArknightsGameData_YoStar/master'
const audioApiRoot =
  'https://api.github.com/repos/PseudoMon/arknights-audio/contents/voice_en'
const audioBranch = 'global-server-voices'

const registeredOperators = [
  { id: 'amiya', charId: 'char_002_amiya' },
  { id: 'texas', charId: 'char_102_texas' },
  { id: 'exusiai', charId: 'char_103_angel' },
  { id: 'silverash', charId: 'char_172_svrash' },
  { id: 'nearl', charId: 'char_148_nearl' },
  { id: 'ptilopsis', charId: 'char_128_plosis' },
  { id: 'myrtle', charId: 'char_151_myrtle' },
  { id: 'lappland', charId: 'char_140_whitew' },
]

async function fetchJson(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'arknights-en-voice-player-data-generator' },
  })

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`)
  }

  return response.json()
}

function categoryFor(title) {
  if (title === 'Greeting') return 'Greeting'

  if (
    /Added to Squad|Squad Leader|Depart|Begin Operation|Selecting Operator|Deployment|In Battle|Result|Operation Failure/i.test(
      title,
    )
  ) {
    return 'Battle'
  }

  return 'Talk'
}

const [englishData, japaneseData] = await Promise.all([
  fetchJson(`${gameDataRoot}/en_US/gamedata/excel/charword_table.json`),
  fetchJson(`${gameDataRoot}/ja_JP/gamedata/excel/charword_table.json`),
])

const englishWords = Object.values(englishData.charWords)
const japaneseWords = new Map(
  Object.values(japaneseData.charWords).map((line) => [line.charWordId, line]),
)

const operatorVoiceRecords = {}

for (const operator of registeredOperators) {
  const audioFiles = await fetchJson(
    `${audioApiRoot}/${operator.charId}?ref=${audioBranch}`,
  )
  const availableFiles = new Set(
    audioFiles
      .filter((entry) => entry.type === 'file' && entry.name.endsWith('.mp3'))
      .map((entry) => entry.name),
  )

  const records = englishWords
    .filter(
      (line) =>
        line.charId === operator.charId &&
        line.wordKey === operator.charId &&
        line.voiceId &&
        line.voiceAsset === `${operator.charId}/${line.voiceId}` &&
        availableFiles.has(`${line.voiceId}.mp3`),
    )
    .sort((left, right) => left.voiceIndex - right.voiceIndex)
    .map((line) => {
      const japaneseLine = japaneseWords.get(line.charWordId)

      if (!japaneseLine) {
        throw new Error(`Japanese text is missing: ${line.charWordId}`)
      }

      return {
        fileCode: line.voiceId,
        label: line.voiceTitle,
        category: categoryFor(line.voiceTitle),
        english: line.voiceText,
        japanese: japaneseLine.voiceText,
        audioPath: `${operator.charId}/${line.voiceId}.mp3`,
      }
    })

  if (records.length === 0) {
    throw new Error(`No playable English voices found for ${operator.id}`)
  }

  const uniqueVoiceIds = new Set(records.map((record) => record.fileCode))
  if (uniqueVoiceIds.size !== records.length) {
    throw new Error(`Duplicate voice IDs found for ${operator.id}`)
  }

  operatorVoiceRecords[operator.id] = records
  console.log(`${operator.id}: ${records.length} voices`)
}

const source = `// This file is generated by scripts/generate-voice-data.mjs.\n// Do not edit it by hand.\n\nexport type OperatorVoiceRecord = {\n  fileCode: string\n  label: string\n  category: 'Talk' | 'Battle' | 'Greeting'\n  english: string\n  japanese: string\n  audioPath: string\n}\n\nexport const operatorVoiceRecords: Record<string, OperatorVoiceRecord[]> = ${JSON.stringify(operatorVoiceRecords, null, 2)}\n`

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const destination = resolve(scriptDirectory, '../src/data/operatorVoices.ts')
await writeFile(destination, source, 'utf8')
