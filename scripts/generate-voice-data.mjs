async function fetchJson(url) {
  const response = await fetch(url, {
    headers: { 'User-Agent': 'arknights-en-voice-player-data-generator' },
  })

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`)
  }

  return response.json()
}

function categoryFor(title) {
  if (title === 'Greeting') return 'Greeting'

  if (
    /Added to Squad|Squad Leader|Depart|Begin Operation|Selecting Operator|Deployment|In Battle|Result|Operation Failure/i.test(
      title,
    )
  ) {
    return 'Battle'
  }

  return 'Talk'
}

const [englishData, japaneseData] = await Promise.all([
  fetchJson(`${gameDataRoot}/en_US/gamedata/excel/charword_table.json`),
  fetchJson(`${gameDataRoot}/ja_JP/gamedata/excel/charword_table.json`),
])

const englishWords = Object.values(englishData.charWords)
const japaneseWords = new Map(
  Object.values(japaneseData.charWords).map((line) => [line.charWordId, line]),
)
const standardVoiceMetadata = new Map(
  englishWords
    .filter(
      (line) =>
        line.wordKey === 'char_002_amiya' &&
        standardVoiceSlots.includes(line.voiceId),
    )
    .map((line) => [
      line.voiceId,
      { label: line.voiceTitle, category: categoryFor(line.voiceTitle) },
    ]),
)

const operatorVoiceRecords = {}

for (const operator of registeredOperators) {
  const audioFiles = await fetchJson(
    `${audioApiRoot}/${operator.charId}?ref=${audioBranch}`,
  )
  const availableFiles = new Set(
    audioFiles
      .filter((entry) => entry.type === 'file' && entry.name.endsWith('.mp3'))
      .map((entry) => entry.name),
  )

  const operatorLines = new Map(
    englishWords
      .filter(
        (line) =>
          line.charId === operator.charId &&
          line.wordKey === operator.charId &&
          line.voiceId &&
          line.voiceAsset === `${operator.charId}/${line.voiceId}` &&
          standardVoiceSlots.includes(line.voiceId),
      )
      .map((line) => [line.voiceId, line]),
  )

  const records = standardVoiceSlots.map((voiceId) => {
    const line = operatorLines.get(voiceId)
    const metadata = standardVoiceMetadata.get(voiceId)
    const japaneseLine = line ? japaneseWords.get(line.charWordId) : null

    if (line && !japaneseLine) {
      throw new Error(`Japanese text is missing: ${line.charWordId}`)
    }
    if (!metadata) {
      throw new Error(`Standard voice metadata is missing: ${voiceId}`)
    }

    return {
      fileCode: voiceId,
      label: line?.voiceTitle ?? metadata.label,
      category: line ? categoryFor(line.voiceTitle) : metadata.category,
      english: line?.voiceText ?? '',
      japanese: japaneseLine?.voiceText ?? '',
      audioPath:
        line && availableFiles.has(`${voiceId}.mp3`)
          ? `${operator.charId}/${voiceId}.mp3`
          : null,
    }
  })

  if (records.length === 0) {
    throw new Error(`No English voice records found for ${operator.id}`)
  }

  const uniqueVoiceIds = new Set(records.map((record) => record.fileCode))
  if (uniqueVoiceIds.size !== records.length) {
    throw new Error(`Duplicate voice IDs found for ${operator.id}`)
  }

  operatorVoiceRecords[operator.id] = records
  const unavailable = records.filter((record) => record.audioPath === null)
  const summary = `${records.length - unavailable.length}/${records.length} playable`
  const missing = unavailable.map((record) => record.fileCode).join(', ')
  console.log(`${operator.id}: ${summary}${missing ? ` (missing: ${missing})` : ''}`)
}

const source = `// This file is generated by scripts/generate-voice-data.mjs.\n// Do not edit it by hand.\n\nexport type OperatorVoiceRecord = {\n  fileCode: string\n  label: string\n  category: 'Talk' | 'Battle' | 'Greeting'\n  english: string\n  japanese: string\n  audioPath: string | null\n}\n\nexport const operatorVoiceRecords: Record<string, OperatorVoiceRecord[]> = ${JSON.stringify(operatorVoiceRecords, null, 2)}\n`

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const destination = resolve(scriptDirectory, '../src/data/operatorVoices.ts')
await writeFile(destination, source, 'utf8')
